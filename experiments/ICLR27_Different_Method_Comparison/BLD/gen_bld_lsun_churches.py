#!/usr/bin/env python3
"""Sample images from one official-architecture BLD EMA checkpoint."""

import argparse
import os
import random
import sys
import time
from pathlib import Path

import numpy as np
import torch
from PIL import Image
from torchvision.utils import save_image


SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parents[2]
sys.path.insert(0, str(REPO_ROOT))

from hparams.defaults.binarygan_default import HparamsBinaryAE  # noqa: E402
from hparams.defaults.sampler_defaults import HparamsBianryLatent  # noqa: E402
from models.binaryae import Generator  # noqa: E402
from models.transformer import TransformerBD  # noqa: E402
from models.binarylatent import BinaryDiffusion  # noqa: E402
from utils.sampler_utils import (  # noqa: E402
    retrieve_autoencoder_components_state_dicts,
)


def parse_args():
    parser = argparse.ArgumentParser(
        description="Generate BLD samples for Churches, Bedrooms, or FFHQ."
    )
    parser.add_argument(
        "--dataset",
        choices=("churches", "bedrooms", "ffhq"),
        default="churches",
        help="Dataset defaults used to construct the BLD and BAE models.",
    )
    parser.add_argument(
        "--checkpoint",
        type=Path,
        default=SCRIPT_DIR / "train_100k" / "saved_models" / "bld_ema_100000.th",
    )
    parser.add_argument(
        "--ae_load_dir",
        type=Path,
        default=REPO_ROOT / "logs" / "BAE_C64",
    )
    parser.add_argument("--ae_load_step", type=int, default=8100000)
    parser.add_argument(
        "--model_total_steps",
        type=int,
        default=64,
        help="Training horizon used by the checkpoint and its time embedding.",
    )
    parser.add_argument(
        "--output_dir",
        type=Path,
        default=SCRIPT_DIR / "fid_result",
        help="Images are written to OUTPUT_DIR/{sampling_steps}/.",
    )
    parser.add_argument(
        "--sampling_steps",
        type=int,
        nargs="+",
        default=[64],
    )
    parser.add_argument("--num_samples", type=int, default=10)
    parser.add_argument(
        "--sample_batch_size",
        type=int,
        default=10,
        help="Number of latent samples generated by this process per batch.",
    )
    parser.add_argument("--decode_batch_size", type=int, default=5)
    parser.add_argument("--temperature", type=float, default=1.0)
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Base seed. Batch seed is seed + rank + batch_index * seed_stride.",
    )
    parser.add_argument("--seed_stride", type=int, default=10)
    parser.add_argument("--rank", type=int, default=0)
    parser.add_argument("--world_size", type=int, default=1)
    parser.add_argument(
        "--resume",
        action="store_true",
        help="Skip complete batches whose expected RGB PNGs already exist.",
    )
    parser.add_argument("--progress_every", type=int, default=10)
    amp_group = parser.add_mutually_exclusive_group()
    amp_group.add_argument(
        "--amp",
        dest="amp",
        action="store_true",
        help="Use automatic mixed precision while sampling and decoding (default).",
    )
    amp_group.add_argument(
        "--no_amp",
        dest="amp",
        action="store_false",
        help="Disable automatic mixed precision.",
    )
    parser.set_defaults(amp=True)
    return parser.parse_args()


def build_hparams(args):
    # Match get_sampler_hparams(): BinaryAE defaults are updated by sampler defaults.
    H = HparamsBinaryAE(args.dataset)
    H.vqgan_batch_size = H.batch_size
    H.update(HparamsBianryLatent(args.dataset))

    # Match the checkpoint's training horizon and time-embedding scale.
    H.sampler = "bld"
    H.dataset = args.dataset
    H.codebook_size = 64
    H.img_size = 256
    H.latent_shape = [1, 16, 16]
    H.total_steps = args.model_total_steps
    H.sample_steps = args.model_total_steps
    H.beta_type = "linear"
    H.loss_final = "mean"
    H.p_flip = True
    H.focal = -1
    H.aux = 0.0
    H.norm_first = True
    H.batch_size = args.sample_batch_size
    H.amp = args.amp
    H.ema = True
    H.ae_load_dir = str(args.ae_load_dir.resolve())
    H.ae_load_step = args.ae_load_step
    return H


def set_seed(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def get_process_shard(num_samples, rank, world_size):
    """Return the contiguous [start, end) sample shard for one rank."""
    samples_per_rank = num_samples // world_size
    remainder = num_samples % world_size
    shard_size = samples_per_rank + int(rank < remainder)
    start = rank * samples_per_rank + min(rank, remainder)
    return start, start + shard_size


def is_valid_rgb_png(path):
    if not path.is_file():
        return False
    try:
        with Image.open(path) as image:
            image.verify()
        with Image.open(path) as image:
            return image.mode == "RGB" and image.size == (256, 256)
    except (OSError, ValueError):
        return False


def load_models(H, checkpoint):
    ae_state = retrieve_autoencoder_components_state_dicts(
        H,
        ["quantize", "generator"],
        remove_component_from_key=True,
    )
    embedding_weight = ae_state.pop("embed.weight").cuda()

    generator = Generator(H)
    generator.load_state_dict(ae_state, strict=False)
    generator = generator.cuda().eval()
    del ae_state

    denoise_fn = TransformerBD(H).cuda()
    sampler = BinaryDiffusion(
        H, denoise_fn, H.codebook_size, embedding_weight
    ).cuda()
    state_dict = torch.load(checkpoint, map_location="cpu")
    incompatible = sampler.load_state_dict(state_dict, strict=False)
    if incompatible.missing_keys or incompatible.unexpected_keys:
        raise RuntimeError(
            "Checkpoint mismatch: "
            f"missing={incompatible.missing_keys}, "
            f"unexpected={incompatible.unexpected_keys}"
        )
    del state_dict
    sampler.eval()
    return sampler, generator, embedding_weight


@torch.no_grad()
def decode_latents(
        H, embedding_weight, generator, latents, batch_size, amp):
    images = []
    for latent in torch.split(latents, batch_size):
        latent = latent.float()
        if H.use_tanh:
            latent = (latent - 0.5) * 2.0
        if not H.norm_first:
            latent = latent / float(H.codebook_size)

        latent = latent @ embedding_weight
        latent = latent.permute(0, 2, 1).reshape(
            latent.shape[0],
            H.emb_dim,
            H.latent_shape[1],
            H.latent_shape[2],
        )
        with torch.cuda.amp.autocast(enabled=amp):
            images.append(generator(latent).float().cpu())
    return torch.cat(images, dim=0)


@torch.no_grad()
def generate_one_setting(
        H, sampler, generator, embedding_weight, args, sampling_steps, shard):
    shard_start, shard_end = shard
    shard_size = shard_end - shard_start
    step_dir = args.output_dir / str(sampling_steps)
    step_dir.mkdir(parents=True, exist_ok=True)
    started = time.time()

    for batch_index, offset in enumerate(
        range(0, shard_size, args.sample_batch_size)
    ):
        current_batch_size = min(args.sample_batch_size, shard_size - offset)
        first_index = shard_start + offset
        paths = [
            step_dir / f"{index:05d}.png"
            for index in range(first_index, first_index + current_batch_size)
        ]

        if args.resume and all(is_valid_rgb_png(path) for path in paths):
            if (
                batch_index % args.progress_every == 0
                or offset + current_batch_size == shard_size
            ):
                print(
                    f"[rank {args.rank}] step={sampling_steps} "
                    f"resume={offset + current_batch_size}/{shard_size}",
                    flush=True,
                )
            continue

        # Match the reference distributed generator:
        # batch_seed = rank + batch_count * 10 + 42.
        # Reseeding every batch and every NFE keeps equal global image indices
        # paired across the five sampling-step settings.
        batch_seed = args.seed + args.rank + batch_index * args.seed_stride
        set_seed(batch_seed)
        with torch.cuda.amp.autocast(enabled=args.amp):
            latents = sampler.sample(
                sample_steps=sampling_steps,
                temp=args.temperature,
                b=current_batch_size,
                return_all=False,
            )

        images = decode_latents(
            H,
            embedding_weight,
            generator,
            latents,
            args.decode_batch_size,
            args.amp,
        )
        if len(images) != current_batch_size:
            raise RuntimeError(
                f"Expected {current_batch_size} images, got {len(images)}"
            )

        for path, image in zip(paths, images):
            temporary_path = path.with_name(f".{path.name}.tmp")
            save_image(image.clamp(0, 1), temporary_path, format="png")
            os.replace(temporary_path, path)

        if (
            batch_index % args.progress_every == 0
            or offset + current_batch_size == shard_size
        ):
            completed = offset + current_batch_size
            elapsed = time.time() - started
            rate = completed / elapsed if elapsed else 0.0
            print(
                f"[rank {args.rank}] step={sampling_steps} "
                f"generated={completed}/{shard_size} "
                f"rate={rate:.2f} images/s seed={batch_seed}",
                flush=True,
            )

    print(
        f"[rank {args.rank}] completed step={sampling_steps}: "
        f"{shard_size} images in {step_dir}",
        flush=True,
    )


def main():
    args = parse_args()
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is required by the BLD sampler.")
    if (
        args.num_samples <= 0
        or args.sample_batch_size <= 0
        or args.decode_batch_size <= 0
    ):
        raise ValueError(
            "num_samples, sample_batch_size, and decode_batch_size must be positive."
        )
    if args.world_size <= 0 or not 0 <= args.rank < args.world_size:
        raise ValueError(
            f"Expected 0 <= rank < world_size, got "
            f"rank={args.rank}, world_size={args.world_size}."
        )
    if args.seed_stride <= args.world_size - 1:
        raise ValueError(
            "seed_stride must exceed world_size - 1 to avoid rank seed collisions."
        )
    if args.progress_every <= 0:
        raise ValueError("progress_every must be positive.")
    if args.model_total_steps <= 0:
        raise ValueError("model_total_steps must be positive.")
    if any(step <= 0 or step > args.model_total_steps for step in args.sampling_steps):
        raise ValueError(
            f"Every sampling step count must be in [1, {args.model_total_steps}]."
        )

    args.checkpoint = args.checkpoint.resolve()
    args.output_dir = args.output_dir.resolve()
    if not args.checkpoint.is_file():
        raise FileNotFoundError(f"BLD checkpoint not found: {args.checkpoint}")

    H = build_hparams(args)
    sampler, generator, embedding_weight = load_models(H, args.checkpoint)
    shard = get_process_shard(args.num_samples, args.rank, args.world_size)
    print(
        f"[rank {args.rank}] loaded EMA checkpoint: {args.checkpoint}; "
        f"global shard=[{shard[0]}, {shard[1]})",
        flush=True,
    )

    for sampling_steps in args.sampling_steps:
        print(
            f"[rank {args.rank}] sampling {shard[1] - shard[0]} images "
            f"with {sampling_steps} steps...",
            flush=True,
        )
        generate_one_setting(
            H,
            sampler,
            generator,
            embedding_weight,
            args,
            sampling_steps,
            shard,
        )


if __name__ == "__main__":
    main()
